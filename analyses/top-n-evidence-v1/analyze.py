"""Replay frozen source ranks and measure complete registered evidence at Top1..5.

Standard library only. Run with --check to compare every generated byte against
the archived report, without overwriting it. No model/network/index operations.
"""
import argparse
import csv
import hashlib
import io
import json
import math
from pathlib import Path
import statistics

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BUNDLE = ROOT / 'experiments/smm-baseline-001'
ROUTES = ('bm25', 'vector', 'union')


def read(path):
    return json.loads(path.read_text())


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build():
    protocol = read(HERE / 'protocol.json')
    snapshot = read(ROOT / 'publication/benchmark-files.json')['files']
    bindings = {}

    def frozen(rel):
        data = (BUNDLE / rel).read_bytes()
        actual = sha(data)
        assert actual == snapshot[rel], f'Frozen input changed: {rel}'
        bindings[rel] = actual
        return json.loads(data)

    cases = frozen('data/cases.json')
    assert len(cases) == 25
    details = []
    witness_checks = 0
    for case in cases:
        cid = case['id']
        corpus = frozen(case['corpus_file'])
        retrieval = frozen(f'data/retrieval/{cid}.json')
        records = {r['id']: r for r in corpus['records']}
        assert len(records) == len(corpus['records'])
        assert retrieval['case_id'] == cid
        assert retrieval['query'] == case['question']
        assert retrieval['clock'] == case['known_at']
        for sid, record in records.items():
            assert sha(record['text'].encode()) == record['source_sha256']
            assert corpus['structure'][sid]['source_sha256'] == record['source_sha256']
        refs = set(case['official_reference_sources'])
        assert refs <= records.keys()
        assert len(refs) == len(case['official_reference_sources'])
        atoms = {}
        for atom in case['requirements']:
            assert atom['id'] not in atoms and atom['witnesses']
            atoms[atom['id']] = atom['witnesses']
            for w in atom['witnesses']:
                r = records[w['source_id']]
                assert r['text'][w['start']:w['end']] == w['quote']
                assert w['source_sha256'] == r['source_sha256']
                assert w['received_at'] == r['received_at']
                assert any(p['role'] == w['role'] and p['start'] <= w['start']
                           and w['end'] <= p['end']
                           for p in corpus['structure'][w['source_id']]['parts'])
                witness_checks += 1
        native = retrieval['native']['native']
        ranks = {}
        for route in ROUTES[:2]:
            items = native[route]
            assert len(items) >= 5
            ids = [x['source_id'] for x in items]
            scores = [x['score'] for x in items]
            assert len(ids) == len(set(ids)) and set(ids) <= records.keys()
            assert all(math.isfinite(s) for s in scores)
            assert all(a >= b for a, b in zip(scores, scores[1:]))
            ranks[route] = {sid: i + 1 for i, sid in enumerate(ids)}
        detail = dict(case_id=cid, question=case['question'],
                      answer_ambiguity=case['answer_ambiguity'], corpus_conversations=len(records),
                      official_reference_sources=sorted(refs),
                      evidence_atoms=[dict(id=aid, witnesses=[dict(**w, ranks={
                          route: ranks[route].get(w['source_id']) for route in ROUTES[:2]})
                          for w in witnesses]) for aid, witnesses in atoms.items()], results={})
        for route in ROUTES:
            cells = []
            for n in range(1, 6):
                routes = ROUTES[:2] if route == 'union' else (route,)
                selected = sorted({x['source_id'] for key in routes for x in native[key][:n]})
                covered = [aid for aid, ws in atoms.items()
                           if any(w['source_id'] in selected for w in ws)]
                missing = sorted(atoms.keys() - set(covered))
                missing_refs = sorted(refs - set(selected))
                cells.append(dict(n=n, selected_sources=selected, candidate_count=len(selected),
                                  source_characters=sum(len(records[s]['text']) for s in selected),
                                  covered_atoms=covered, missing_atoms=missing,
                                  necessary_complete=not missing,
                                  covered_reference_count=len(refs) - len(missing_refs),
                                  missing_references=missing_refs, official_complete=not missing_refs))
            assert all(set(a['selected_sources']) <= set(b['selected_sources'])
                       for a, b in zip(cells, cells[1:]))
            detail['results'][route] = cells
        details.append(detail)

    aggregates = []
    for slice_name, subset in [('all_25', details), ('clear_23', [c for c in details if not c['answer_ambiguity']])]:
        for route in ROUTES:
            for n in range(1, 6):
                cells = [c['results'][route][n - 1] for c in subset]
                total_atoms = sum(len(c['evidence_atoms']) for c in subset)
                total_refs = sum(len(c['official_reference_sources']) for c in subset)
                complete = sum(c['necessary_complete'] for c in cells)
                official = sum(c['official_complete'] for c in cells)
                aggregates.append(dict(slice=slice_name, route=route, n=n, cases=len(subset),
                    complete_cases=complete, completeness_rate=complete / len(subset),
                    all_official_cases=official, all_official_rate=official / len(subset),
                    covered_atoms=sum(len(c['covered_atoms']) for c in cells), total_atoms=total_atoms,
                    covered_references=sum(c['covered_reference_count'] for c in cells), total_references=total_refs,
                    mean_candidates=statistics.mean(c['candidate_count'] for c in cells),
                    min_candidates=min(c['candidate_count'] for c in cells),
                    max_candidates=max(c['candidate_count'] for c in cells),
                    mean_source_characters=statistics.mean(c['source_characters'] for c in cells),
                    median_source_characters=statistics.median(c['source_characters'] for c in cells),
                    incomplete_cases=[c['case_id'] for c in subset if not c['results'][route][n - 1]['necessary_complete']]))
    assert sum(len(c['evidence_atoms']) for c in details) == 36
    assert sum(len(c['official_reference_sources']) for c in details) == 43
    for route, expected in [('bm25', (25, 36, 43)), ('vector', (24, 35, 41)), ('union', (25, 36, 43))]:
        row = next(a for a in aggregates if a['slice'] == 'all_25' and a['route'] == route and a['n'] == 5)
        assert (row['complete_cases'], row['covered_atoms'], row['covered_references']) == expected
    report = dict(analysis_id=protocol['id'], protocol_sha256=sha((HERE / 'protocol.json').read_bytes()),
                  new_model_calls=0, new_embedding_calls=0, frozen_input_hashes=bindings,
                  verified_witnesses=witness_checks, aggregates=aggregates, cases=details)
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=list(aggregates[0]))
    writer.writeheader()
    for row in aggregates:
        writer.writerow({**row, 'incomplete_cases': ';'.join(row['incomplete_cases'])})
    lines = ['# Per-case registered evidence coverage', '',
             'Minimum cutoff within 1–5; `>5` means incomplete in the tested cutoffs. '
             'Each union cutoff takes that many from **both** routes, then deduplicates.', '',
             '| Case | Atoms | Official refs | BM25 necessary / official | Vector necessary / official | Union necessary / official |',
             '|---|---:|---:|---|---|---|']
    def first(c, route, metric):
        return next((str(v['n']) for v in c['results'][route] if v[metric]), '>5')
    for c in details:
        cells = [f"{first(c, route, 'necessary_complete')} / {first(c, route, 'official_complete')}" for route in ROUTES]
        lines.append(f"| [{c['case_id']}](../../docs/cases/{c['case_id']}.md) | {len(c['evidence_atoms'])} | {len(c['official_reference_sources'])} | " + ' | '.join(cells) + ' |')
    lines.extend(['', '## Missing necessary evidence by cutoff', ''])
    for a in aggregates:
        if a['slice'] == 'all_25':
            lines.append(f"- {a['route']} Top{a['n']}: " + (', '.join(a['incomplete_cases']) or 'none'))
    return {'results.json': json.dumps(report, ensure_ascii=False, indent=2) + '\n',
            'summary.csv': stream.getvalue(), 'case-coverage.md': '\n'.join(lines) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = build()
    for name, content in files.items():
        path = HERE / name
        if args.check:
            assert path.read_bytes() == content.encode(), f'Replay mismatch: {name}'
        else:
            with path.open('x', newline='') as f:
                f.write(content)
    print(json.dumps(dict(passed=True, mode='check' if args.check else 'create',
                          files=list(files), cases=25, model_calls=0, embedding_calls=0)))


if __name__ == '__main__':
    main()
